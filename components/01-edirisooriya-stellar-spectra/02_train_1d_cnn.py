# 02_train_1d_cnn.py
"""
Training script for 1‑D Convolutional Neural Network (ResNet‑style) on stellar spectra.

The script expects processed data files `train.npz` and `val.npz` generated by
`01_data_preprocess.py`. It builds a simple 1‑D ResNet, trains with AdamW,
uses early‑stopping on validation loss, and saves the best model checkpoint.

Usage:
    python 02_train_1d_cnn.py --data_dir <path_to_processed> --out_dir <path_to_models>
"""

import os
import argparse
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import TensorDataset, DataLoader


class BasicBlock(nn.Module):
    """A minimal 1‑D ResNet block.
    Consists of Conv1‑D -> BatchNorm -> ReLU -> Conv1‑D -> BatchNorm.
    Skip connection adds input to output before final ReLU.
    """

    def __init__(self, in_channels, out_channels, kernel_size=3, stride=1, padding=1):
        super().__init__()
        self.conv1 = nn.Conv1d(in_channels, out_channels, kernel_size, stride, padding, bias=False)
        self.bn1 = nn.BatchNorm1d(out_channels)
        self.relu = nn.ReLU(inplace=True)
        self.conv2 = nn.Conv1d(out_channels, out_channels, kernel_size, 1, padding, bias=False)
        self.bn2 = nn.BatchNorm1d(out_channels)
        self.downsample = (
            nn.Sequential(
                nn.Conv1d(in_channels, out_channels, kernel_size=1, stride=stride, bias=False),
                nn.BatchNorm1d(out_channels),
            )
            if in_channels != out_channels or stride != 1
            else nn.Identity()
        )

    def forward(self, x):
        identity = self.downsample(x)
        out = self.conv1(x)
        out = self.bn1(out)
        out = self.relu(out)
        out = self.conv2(out)
        out = self.bn2(out)
        out += identity
        out = self.relu(out)
        return out


class ResNet1D(nn.Module):
    """Simple ResNet for 1‑D spectra.
    Architecture: Conv1‑D stem -> N residual blocks -> GlobalAvgPool -> Linear.
    """

    def __init__(self, num_classes=7, channels=[64, 128, 256], block=BasicBlock):
        super().__init__()
        self.stem = nn.Sequential(
            nn.Conv1d(1, channels[0], kernel_size=7, stride=2, padding=3, bias=False),
            nn.BatchNorm1d(channels[0]),
            nn.ReLU(inplace=True),
            nn.MaxPool1d(kernel_size=3, stride=2, padding=1),
        )
        layers = []
        in_c = channels[0]
        for out_c in channels:
            layers.append(block(in_c, out_c))
            in_c = out_c
        self.layers = nn.Sequential(*layers)
        self.global_pool = nn.AdaptiveAvgPool1d(1)
        self.fc = nn.Linear(in_c, num_classes)

    def forward(self, x):
        # x shape: (batch, length)
        x = x.unsqueeze(1)  # add channel dim -> (batch, 1, length)
        x = self.stem(x)
        x = self.layers(x)
        x = self.global_pool(x)
        x = torch.flatten(x, 1)
        x = self.fc(x)
        return x


def load_data(npz_path):
    data = np.load(npz_path)
    X = torch.tensor(data['X'], dtype=torch.float32)
    y = torch.tensor(data['y'], dtype=torch.long)
    return TensorDataset(X, y)


def train_one_epoch(model, loader, criterion, optimizer, device):
    model.train()
    running_loss = 0.0
    for X, y in loader:
        X, y = X.to(device), y.to(device)
        optimizer.zero_grad()
        outputs = model(X)
        loss = criterion(outputs, y)
        loss.backward()
        optimizer.step()
        running_loss += loss.item() * X.size(0)
    return running_loss / len(loader.dataset)


def evaluate(model, loader, criterion, device):
    model.eval()
    loss_sum = 0.0
    correct = 0
    total = 0
    with torch.no_grad():
        for X, y in loader:
            X, y = X.to(device), y.to(device)
            outputs = model(X)
            loss = criterion(outputs, y)
            loss_sum += loss.item() * X.size(0)
            _, predicted = torch.max(outputs, 1)
            total += y.size(0)
            correct += (predicted == y).sum().item()
    avg_loss = loss_sum / total
    acc = correct / total
    return avg_loss, acc


def main(data_dir, out_dir, epochs=50, batch_size=64, patience=5):
    os.makedirs(out_dir, exist_ok=True)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    train_set = load_data(os.path.join(data_dir, 'train.npz'))
    val_set = load_data(os.path.join(data_dir, 'val.npz'))
    train_loader = DataLoader(train_set, batch_size=batch_size, shuffle=True)
    val_loader = DataLoader(val_set, batch_size=batch_size, shuffle=False)
    # Dynamically infer number of classes from training labels
    y_train = train_set.tensors[1]
    num_classes = int(y_train.max().item()) + 1
    model = ResNet1D(num_classes=num_classes).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
    best_val_loss = float('inf')
    epochs_no_improve = 0
    for epoch in range(1, epochs + 1):
        train_loss = train_one_epoch(model, train_loader, criterion, optimizer, device)
        val_loss, val_acc = evaluate(model, val_loader, criterion, device)
        print(f"Epoch {epoch:03d}: TrainLoss={train_loss:.4f} ValLoss={val_loss:.4f} ValAcc={val_acc:.4f}")
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            epochs_no_improve = 0
            torch.save(model.state_dict(), os.path.join(out_dir, 'best_model.pth'))
            print('  --> New best model saved')
        else:
            epochs_no_improve += 1
            if epochs_no_improve >= patience:
                print('Early stopping triggered')
                break
    print('Training finished. Best val loss:', best_val_loss)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Train 1D ResNet on stellar spectra')
    parser.add_argument('--data_dir', required=True, help='Directory containing train.npz and val.npz')
    parser.add_argument('--out_dir', required=True, help='Directory to store model checkpoints')
    args = parser.parse_args()
    main(args.data_dir, args.out_dir)
